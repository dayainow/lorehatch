export function friendship(id,pets){
 const pair=pairs.find(([a,b])=>a===id||b===id);
 if(!pair)return null;
 const [a,b,title,hint,ending]=pair;
 const complete=[a,b].every(key=>pets.some(p=>p.id===key&&p.stage==='adult'&&p.care?.includes('adult')));
 return {other:a===id?b:a,title,hint,ending,complete};
}

// Only recommend selectable eggs; ties retain catalog order.
export function recommendFriend(available,pets){
 return available.find(id=>{
  const bond=friendship(id,pets);
  return bond && pets.some(p=>p.id===bond.other&&p.stage==='adult');
 }) ?? available.find(id=>{
  const bond=friendship(id,pets);
  return bond && pets.some(p=>p.id===bond.other);
 }) ?? available[0] ?? null;
}
